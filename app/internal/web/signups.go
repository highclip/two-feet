const (
	joinLimit        = 30
	joinWindow       = 10 * time.Minute
	joinAction       = "join_space"
	maxSignupFormLen = 1 << 10

	leftLine     = "Law of two feet. You've left."
	leftSeatLine = "Law of two feet. You've left, and your seat went to the next person."
	leftLineLine = "You've left the waitlist."
)

func (s *Server) registerSignups(mux *http.ServeMux) {
	mux.Handle("POST /e/{slug}/spaces/{space}/join", auth.RequirePerson(http.HandlerFunc(s.joinSpace)))
	mux.Handle("POST /e/{slug}/spaces/{space}/leave", auth.RequirePerson(http.HandlerFunc(s.leaveSpace)))
	mux.Handle("POST /e/{slug}/spaces/{space}/leave/undo", auth.RequirePerson(http.HandlerFunc(s.undoLeave)))
}

func leaveUndoKey(spaceID, personID string) string { return "leave:" + spaceID + ":" + personID }

func isHtmx(r *http.Request) bool { return r.Header.Get("HX-Request") != "" }

// signupRequest loads what every signup action needs and checks join_or_leave_space.
func (s *Server) signupRequest(w http.ResponseWriter, r *http.Request) (store.Event, store.Space, store.Person, bool) {
	e, ok := s.event(w, r)
	if !ok {
		return store.Event{}, store.Space{}, store.Person{}, false
	}
	sp, ok := s.spaceForRequest(w, r, e)
	if !ok {
		return store.Event{}, store.Space{}, store.Person{}, false
	}
	person, _ := auth.Current(r.Context())
	if person.DisplayName == "" {
		s.forbidden(w, r, e, "Choose a name first, then join.")
		return store.Event{}, store.Space{}, store.Person{}, false
	}
	if !auth.HasRole(person, store.RoleAttendee, store.RoleSponsorRep) {
		s.forbidden(w, r, e, "Organizers run the room, so joining is for attendees and sponsor reps.")
		return store.Event{}, store.Space{}, store.Person{}, false
	}
	return e, sp, person, true
}

// answer re-renders a space for the person who just acted: the live section for htmx, or the whole
// page or a redirect otherwise. edit fills in what's specific to this answer.
func (s *Server) answer(w http.ResponseWriter, r *http.Request, e store.Event, sp store.Space, person store.Person, status int, toast views.SpaceToast, edit func(*views.SpaceView)) {
	current, err := s.store.SpaceByID(r.Context(), sp.ID)
	if err != nil {
		s.serverError(w, err)
		return
	}
	v, err := s.spaceView(r.Context(), e, current, &person)
	if err != nil {
		s.serverError(w, err)
		return
	}
	if edit != nil {
		edit(&v)
	}
	if isHtmx(r) {
		// htmx doesn't swap error statuses, and a refusal here is a sentence in place, not a failure.
		s.render(w, r, http.StatusOK, views.SeatsResponse(v, toast))
		return
	}
	if status == http.StatusSeeOther {
		http.Redirect(w, r, spaceURL(e.Slug, sp.Slug), http.StatusSeeOther) // #nosec G710 -- the slug is generated by the server
		return
	}
	v.Toast = toast
	page := s.livePage(r, e, current.Title, spaceTopic(current))
	s.render(w, r, status, views.SpacePage(page, v, false, spacesURL(e.Slug)+"/new"))
}

// refuse answers a refused action with one sentence in the space's own card.
func (s *Server) refuse(w http.ResponseWriter, r *http.Request, e store.Event, sp store.Space, person store.Person, status int, problem string) {
	s.answer(w, r, e, sp, person, status, views.SpaceToast{}, func(v *views.SpaceView) { v.Problem = problem })
}

// refusalFor maps a store error to a sentence for the person, or reports false.
func refusalFor(err error) (status int, text string, ok bool) {
	switch {
	case errors.Is(err, store.ErrSpaceCancelled):
		return http.StatusConflict, "This space was cancelled, so it can't be changed. Start a new one instead.", true
	case errors.Is(err, store.ErrJoinClosed):
		return http.StatusConflict, "This one's been going a while, so it's closed to new people. Find another nearby.", true
	case errors.Is(err, store.ErrSpaceOver):
		return http.StatusConflict, "This space has finished. Find another nearby.", true
	case errors.Is(err, store.ErrHostCannotLeave):
		return http.StatusConflict, "You're hosting this one, so cancel it instead of leaving.", true
	case errors.Is(err, store.ErrNotFound):
		return http.StatusNotFound, "That space isn't here any more. Reload and try again.", true
	}
	return 0, "", false
}

func readSignupForm(w http.ResponseWriter, r *http.Request) bool {
	r.Body = http.MaxBytesReader(w, r.Body, maxSignupFormLen)
	if err := r.ParseForm(); err != nil {
		http.Error(w, "That form was too long. Reload and try again.", http.StatusRequestEntityTooLarge)
		return false
	}
	return true
}

func (s *Server) joinSpace(w http.ResponseWriter, r *http.Request) {
	ctx, span := telemetry.Start(r.Context(), "space.join")
	defer span.End()
	r = r.WithContext(ctx)

	e, sp, person, ok := s.signupRequest(w, r)
	if !ok || !readSignupForm(w, r) {
		return
	}
	in := store.JoinInput{SpaceID: sp.ID, PersonID: person.ID, Now: time.Now()}
	if leave := r.PostFormValue("leave"); uuidShape.MatchString(leave) {
		in.LeaveSpaceID = leave
	}

	if allowed, retryAt := s.limiter.Allow(person.ID, joinAction, joinLimit, joinWindow); !allowed {
		s.refuse(w, r, e, sp, person, http.StatusTooManyRequests,
			fmt.Sprintf("You've joined a lot of spaces just now. You can join another at %s.", retryAt.In(eventLocation(e)).Format("3:04")))
		return
	}

	res, err := s.store.JoinSpace(ctx, in)
	if err != nil {
		s.limiter.Release(person.ID, joinAction)
		var clash *store.OverlapError
		if errors.As(err, &clash) {
			s.answer(w, r, e, sp, person, http.StatusConflict, views.SpaceToast{}, func(v *views.SpaceView) { v.Overlap = clash })
			return
		}
		if status, text, ok := refusalFor(err); ok {
			s.refuse(w, r, e, sp, person, status, text)
			return
		}
		s.serverError(w, err)
		return
	}
	if !res.Changed {
		s.limiter.Release(person.ID, joinAction)
	} else {
		telemetry.RecordSignup(ctx)
		s.publishSpaceChanged(ctx, sp.ID)
		if res.LeftSpaceID != "" {
			s.tellPromoted(ctx, e, res.LeftSpaceID, res.Promoted)
			s.publishSpaceChanged(ctx, res.LeftSpaceID)
		}
	}
	s.answer(w, r, e, sp, person, http.StatusSeeOther, views.SpaceToast{}, nil)
}

func (s *Server) leaveSpace(w http.ResponseWriter, r *http.Request) {
	ctx, span := telemetry.Start(r.Context(), "space.leave")
	defer span.End()
	r = r.WithContext(ctx)

	e, sp, person, ok := s.signupRequest(w, r)
	if !ok {
		return
	}
	res, err := s.store.LeaveSpace(ctx, sp.ID, person.ID, time.Now())
	if err != nil {
		if status, text, ok := refusalFor(err); ok {
			s.refuse(w, r, e, sp, person, status, text)
			return
		}
		s.serverError(w, err)
		return
	}

	var toast views.SpaceToast
	if res.Changed {
		s.publishSpaceChanged(ctx, sp.ID)
		toast = s.leaveToast(ctx, e, sp, person, res)
	}
	s.answer(w, r, e, sp, person, http.StatusSeeOther, toast, nil)
}

// leaveToast tells the person what happened, offering Undo only when nobody took the seat (D2).
func (s *Server) leaveToast(ctx context.Context, e store.Event, sp store.Space, person store.Person, res store.LeaveResult) views.SpaceToast {
	if len(res.Promoted) > 0 {
		s.tellPromoted(ctx, e, sp.ID, res.Promoted)
		return views.SpaceToast{Text: leftSeatLine}
	}
	s.undo.start(leaveUndoKey(sp.ID, person.ID))
	text := leftLine
	if !res.WasGoing {
		text = leftLineLine
	}
	return views.SpaceToast{Text: text, UndoURL: spaceURL(e.Slug, sp.Slug) + "/leave/undo"}
}

func (s *Server) undoLeave(w http.ResponseWriter, r *http.Request) {
	ctx, span := telemetry.Start(r.Context(), "space.undo_leave")
	defer span.End()
	r = r.WithContext(ctx)

	e, sp, person, ok := s.signupRequest(w, r)
	if !ok {
		return
	}
	key := leaveUndoKey(sp.ID, person.ID)
	clear := views.SpaceToast{Clear: true}

	if !s.undo.open(key) {
		// A second tap can land here with them already back: only say it's too late if it is.
		current, err := s.store.SignupOf(ctx, sp.ID, person.ID)
		if err != nil {
			s.serverError(w, err)
			return
		}
		if current.Status != "" {
			s.answer(w, r, e, sp, person, http.StatusSeeOther, clear, nil)
			return
		}
		s.refuse(w, r, e, sp, person, http.StatusConflict, "It's too late to undo that. Join again instead.")
		return
	}

	err := s.store.UndoLeave(ctx, sp.ID, person.ID, time.Now())
	if err != nil {
		var clash *store.OverlapError
		switch {
		case errors.Is(err, store.ErrSeatTaken):
			s.refuse(w, r, e, sp, person, http.StatusConflict, "Someone took that seat. Join again to get the next one.")
			return
		case errors.As(err, &clash):
			s.refuse(w, r, e, sp, person, http.StatusConflict, fmt.Sprintf("You've joined %s since. Leave it first, then come back.", clash.Title))
			return
		case errors.Is(err, store.ErrNotLeft):
			s.answer(w, r, e, sp, person, http.StatusSeeOther, clear, nil)
			return
		}
		if status, text, ok := refusalFor(err); ok {
			s.refuse(w, r, e, sp, person, status, text)
			return
		}
		s.serverError(w, err)
		return
	}
	s.undo.close(key)
	s.publishSpaceChanged(ctx, sp.ID)
	s.answer(w, r, e, sp, person, http.StatusSeeOther, clear, nil)
}

// tellPromoted says "You're in" to everyone who just moved off the waitlist.
func (s *Server) tellPromoted(ctx context.Context, e store.Event, spaceID string, promoted []string) {
	if len(promoted) == 0 {
		return
	}
	sp, err := s.store.SpaceByID(ctx, spaceID)
	if err != nil {
		s.log.Error("load space to tell promoted", "err", err, "space", spaceID)
		return
	}
	s.notify(ctx, promoted, "", "You're in! A seat opened at "+sp.Title, spaceURL(e.Slug, sp.Slug))
}
